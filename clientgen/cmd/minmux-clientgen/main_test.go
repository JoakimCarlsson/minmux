package main

import (
	"encoding/json"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/joakimcarlsson/minmux/openapi"
	"github.com/joakimcarlsson/minmux/router"
)

type todo struct {
	ID    int    `json:"id"`
	Title string `json:"title"`
}

// specFile writes a real minmux-derived document to disk, so the CLI is
// tested against the same JSON a server would serve rather than a
// hand-written stub.
func specFile(t *testing.T, dir string) string {
	t.Helper()
	r := router.New()
	r.Get("/todos/{id}", func(_ *router.Context, _ struct {
		ID int `path:"id"`
	}) {
	},
		openapi.OperationID("getTodo"),
		openapi.ReturnsBody[todo](http.StatusOK, "A todo"),
	)
	doc := openapi.NewGenerator(
		openapi.Info{Title: "CLI", Version: "1"},
	).Spec(r)

	data, err := json.Marshal(doc)
	if err != nil {
		t.Fatalf("marshaling spec: %v", err)
	}
	path := filepath.Join(dir, "openapi.json")
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatalf("writing spec: %v", err)
	}
	return path
}

func TestRun_GeneratesFromSpecFile(t *testing.T) {
	dir := t.TempDir()
	spec := specFile(t, dir)
	out := filepath.Join(dir, "client")

	err := run([]string{
		"-spec", spec, "-package", "cliclient", "-out", out,
	}, nil, io.Discard)
	if err != nil {
		t.Fatalf("run: %v", err)
	}

	for _, name := range []string{
		"client.gen.go", "types.gen.go", "operations.gen.go",
	} {
		if _, err := os.Stat(filepath.Join(out, name)); err != nil {
			t.Errorf("expected %s: %v", name, err)
		}
	}
	ops := readFile(t, filepath.Join(out, "operations.gen.go"))
	if !strings.Contains(ops, "func (c *Client) GetTodo(") {
		t.Errorf("missing generated method:\n%s", ops)
	}
	if !strings.Contains(ops, "// Code generated by minmux-clientgen -spec") {
		t.Errorf("header should record the invoking command:\n%s", ops)
	}
}

func TestRun_ReadsSpecFromStdin(t *testing.T) {
	dir := t.TempDir()
	spec := readFile(t, specFile(t, dir))
	out := filepath.Join(dir, "client")

	err := run([]string{
		"-spec", "-", "-package", "cliclient", "-out", out,
	}, strings.NewReader(spec), io.Discard)
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	if _, err := os.Stat(filepath.Join(out, "types.gen.go")); err != nil {
		t.Errorf("expected generated types: %v", err)
	}
}

func TestRun_HonorsClientAndCommandFlags(t *testing.T) {
	dir := t.TempDir()
	spec := specFile(t, dir)
	out := filepath.Join(dir, "client")

	err := run([]string{
		"-spec", spec,
		"-package", "cliclient",
		"-out", out,
		"-client", "TodoClient",
		"-command", "make client",
	}, nil, io.Discard)
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	ops := readFile(t, filepath.Join(out, "operations.gen.go"))
	if !strings.Contains(ops, "func (c *TodoClient) GetTodo(") {
		t.Errorf("client type not renamed:\n%s", ops)
	}
	if !strings.HasPrefix(
		ops,
		"// Code generated by make client. DO NOT EDIT.",
	) {
		t.Errorf("command flag not recorded:\n%s", ops)
	}
}

func TestRun_Errors(t *testing.T) {
	dir := t.TempDir()
	spec := specFile(t, dir)

	bad := filepath.Join(dir, "bad.json")
	if err := os.WriteFile(bad, []byte("{not json"), 0o644); err != nil {
		t.Fatalf("writing bad spec: %v", err)
	}
	empty := filepath.Join(dir, "empty.json")
	if err := os.WriteFile(
		empty,
		[]byte(`{"openapi":"3.2.0"}`),
		0o644,
	); err != nil {
		t.Fatalf("writing empty spec: %v", err)
	}

	cases := []struct {
		name string
		args []string
		want string
	}{
		{
			"missing flags",
			[]string{"-spec", spec},
			"are all required",
		},
		{
			"missing file",
			[]string{
				"-spec",
				filepath.Join(dir, "nope.json"),
				"-package",
				"p",
				"-out",
				dir,
			},
			"reading",
		},
		{
			"malformed json",
			[]string{"-spec", bad, "-package", "p", "-out", dir},
			"parsing",
		},
		{
			"no paths",
			[]string{"-spec", empty, "-package", "p", "-out", dir},
			"declares no paths",
		},
		{
			"invalid package",
			[]string{"-spec", spec, "-package", "not valid", "-out", dir},
			"not a valid Go package name",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := run(tc.args, nil, io.Discard)
			if err == nil {
				t.Fatalf("want an error containing %q, got nil", tc.want)
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("want %q, got %v", tc.want, err)
			}
		})
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}
	return string(data)
}
